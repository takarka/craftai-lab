  static CourseLevel? getLevelByContentId(
    String contentId, {
    String locale = 'ru',
  }) {
    for (final level in getLevels(locale: locale)) {
      if (level.contentId == contentId) return level;
    }
    return null;
  }

  static List<CourseLevel> get allLevels => levelsRu;
  static List<CourseLevel> get levels => levelsRu;

  /// Returns localized course levels for the specified [locale] ('ru' or 'kk').
  static List<CourseLevel> getLevels({String locale = 'ru'}) {
    if (locale == 'kk' || locale.startsWith('kk')) {
      return levelsKk;
    }
    return levelsRu;
  }

  /// Returns localized course level by [id] for the specified [locale] ('ru' or 'kk').
  static CourseLevel? getLevel(int id, {String locale = 'ru'}) {
    final list = getLevels(locale: locale);
    try {
      return list.firstWhere((lvl) => lvl.id == id);
    } catch (_) {
      try {
        return levelsRu.firstWhere((lvl) => lvl.id == id);
      } catch (_) {
        return null;
      }
    }
  }

