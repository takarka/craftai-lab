/// Sample pedagogical documents and evaluation pairs for Level 3 (RAG).
/// Fully free of student PII (no names, no IIN, no personal phone numbers or grades).
@immutable
class RagQueryPair {
  const RagQueryPair({
    required this.queryRu,
    required this.queryKk,
    required this.expectedKeywordRu,
    required this.expectedKeywordKk,
    required this.isHit,
    required this.descriptionRu,
    required this.descriptionKk,
  });

  final String queryRu;
  final String queryKk;
  final String expectedKeywordRu;
  final String expectedKeywordKk;
  final bool isHit;
  final String descriptionRu;
  final String descriptionKk;

  String localizedQuery(bool isKk) => isKk ? queryKk : queryRu;
  String localizedKeyword(bool isKk) =>
      isKk ? expectedKeywordKk : expectedKeywordRu;
  String localizedDescription(bool isKk) =>
      isKk ? descriptionKk : descriptionRu;
}

@immutable
class SampleDocument {
  const SampleDocument({
    required this.id,
    required this.titleRu,
    required this.titleKk,
    required this.contentRu,
    required this.contentKk,
    required this.fileName,
  });

  final String id;
  final String titleRu;
  final String titleKk;
  final String contentRu;
  final String contentKk;
  final String fileName;

  String localizedTitle(bool isKk) => isKk ? titleKk : titleRu;
  String localizedContent(bool isKk) => isKk ? contentKk : contentRu;
}

